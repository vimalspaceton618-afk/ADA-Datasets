"""Independent, aggregate-only language and full-pool curation evaluations.

All reports intentionally omit input text, user identifiers and per-document
human labels. Human labels are NOT generated by the curator. Metrics apply only
to the labeled sample; representative sampling and adjudication are external.
"""
from __future__ import annotations

from collections import Counter, defaultdict
import hashlib
import json
import math
from pathlib import Path
import re

from .core import file_digest
from .lid import LanguagePrediction

_LANGS = ("en", "ta", "hi", "other")
_HEX = re.compile(r"[0-9a-f]{64}\Z")


def _safe_fraction(numerator: int, denominator: int) -> float | None:
    return round(numerator / denominator, 6) if denominator else None


def _wilson(successes: int, total: int, z: float = 1.96) -> list[float] | None:
    """Approximate 95% Wilson interval for a binomial proportion (not causal)."""
    if total <= 0:
        return None
    p = successes / total
    z2 = z * z
    denom = 1 + z2 / total
    center = (p + z2 / (2 * total)) / denom
    margin = z * math.sqrt((p * (1 - p) + z2 / (4 * total)) / total) / denom
    return [round(max(0.0, center - margin), 6),
            round(min(1.0, center + margin), 6)]


def _confusion_metrics(counts: Counter) -> dict:
    tp, fp, tn, fn = (counts[key] for key in ("tp", "fp", "tn", "fn"))
    return {
        "tp": tp, "fp": fp, "tn": tn, "fn": fn,
        "precision": _safe_fraction(tp, tp + fp),
        "recall": _safe_fraction(tp, tp + fn),
        "specificity": _safe_fraction(tn, tn + fp),
        "f1": _safe_fraction(2 * tp, 2 * tp + fp + fn),
        "precision_wilson95": _wilson(tp, tp + fp),
        "recall_wilson95": _wilson(tp, tp + fn),
    }


def evaluate_language_id(model, gold_path: Path, *,
                         min_confidence: float = 0.80,
                         max_rows: int = 100_000) -> dict:
    """Read independently gold-labeled JSONL with text and language fields.

    Supported target labels en/ta/hi plus 'other'. Other ISO codes map to
    'other', but should be represented in the gold set to test rejection.
    """
    if not 0 < min_confidence <= 1:
        raise ValueError("min_confidence must be within (0,1]")
    if not 1 <= max_rows <= 1_000_000:
        raise ValueError("invalid max_rows")
    model_info = model.metadata()
    if not isinstance(model_info, dict) or not isinstance(
            model_info.get("model_sha256"), str):
        raise ValueError("model must supply metadata and a SHA-256")
    count = 0
    counts: dict[str, Counter] = {lang: Counter() for lang in _LANGS}
    confusion: dict[str, Counter] = {lang: Counter() for lang in _LANGS}
    with Path(gold_path).open(encoding="utf-8") as stream:
        for line_num, line in enumerate(stream, 1):
            if not line.strip():
                continue
            if count >= max_rows:
                raise ValueError("gold language sample cap exceeded")
            row = json.loads(line)
            if (not isinstance(row, dict) or not isinstance(row.get("text"), str) or
                    not row["text"].strip() or
                    not isinstance(row.get("language"), str) or
                    not re.fullmatch(r"[a-z]{2,3}|other", row["language"])):
                raise ValueError(f"invalid language gold row {line_num}")
            truth = row["language"] if row["language"] in _LANGS else "other"
            prediction = model.predict(row["text"])
            if not isinstance(prediction, LanguagePrediction):
                raise ValueError("invalid model prediction type")
            predicted = (prediction.language
                         if prediction.language in _LANGS else "other")
            if prediction.confidence < min_confidence:
                predicted = "abstain"
            confusion[truth][predicted] += 1
            counts[truth]["support"] += 1
            if predicted != "abstain":
                counts[truth]["predictions"] += 1
                if predicted == truth:
                    counts[truth]["correct"] += 1
            else:
                counts[truth]["abstained"] += 1
            count += 1
    emitted = sum(x["predictions"] for x in counts.values())
    correct = sum(x["correct"] for x in counts.values())
    result = {
        "schema_version": 1,
        "kind": "ada-lid-independent-language-evaluation",
        "model": model_info,
        "gold_file_sha256": file_digest(Path(gold_path)),
        "rows": count,
        "confidence_threshold": min_confidence,
        "coverage": _safe_fraction(emitted, count),
        "accuracy_on_non_abstained": _safe_fraction(correct, emitted),
        "correct_over_all": _safe_fraction(correct, count),
        "confusion_by_gold": {lang: dict(sorted(confusion[lang].items()))
                              for lang in _LANGS},
        "by_gold": {
            lang: {
                "support": counts[lang]["support"],
                "predictions": counts[lang]["predictions"],
                "abstained": counts[lang]["abstained"],
                "recall_with_abstentions": _safe_fraction(
                    counts[lang]["correct"], counts[lang]["support"]),
                "conditional_accuracy": _safe_fraction(
                    counts[lang]["correct"], counts[lang]["predictions"]),
            } for lang in _LANGS
        },
        "limitations": [
            "Gold language labels must be independently annotated and reviewed.",
            "Results are test-sample metrics, not proof of accuracy on web-scale or code-mixed text.",
            "Confidence values are model scores, not calibrated error probabilities.",
            "No text or individual predictions are written to the report.",
        ],
    }
    return result


def evaluate_filter(snapshot: Path, original_input: Path, gold_path: Path,
                    *, max_labels: int = 100_000) -> dict:
    """Measure curator accept/reject against independent labels for input lines.

    Gold rows: {line: positive integer, input_line_sha256: 64hex,
                should_keep: boolean, language?: en|ta|hi|other}.
    Requires the precise ordered raw input and its matching immutable snapshot.
    Refuses derived revocation snapshots (no direct one-to-one original decisions).
    """
    from .cli import validate_output
    snapshot, original_input, gold_path = map(
        Path, (snapshot, original_input, gold_path))
    validate_output(snapshot)
    manifest = json.loads((snapshot / "manifest.json").read_text())
    if "lineage" in manifest or manifest.get("input_sha256") != file_digest(original_input):
        raise ValueError("requires an original curation snapshot and exact raw input bytes")
    if not 1 <= max_labels <= 1_000_000:
        raise ValueError("invalid max_labels")
    labels = {}
    with gold_path.open(encoding="utf-8") as source:
        for n, line in enumerate(source, 1):
            if not line.strip():
                continue
            if len(labels) >= max_labels:
                raise ValueError("human-label sample cap exceeded")
            entry = json.loads(line)
            if not isinstance(entry, dict):
                raise ValueError(f"invalid human label {n}")
            line_no = entry.get("line")
            line_hash = entry.get("input_line_sha256")
            should_keep = entry.get("should_keep")
            lang = entry.get("language", "unknown")
            if (type(line_no) is not int or line_no < 1 or
                    line_no in labels or
                    not isinstance(line_hash, str) or
                    not _HEX.fullmatch(line_hash) or
                    type(should_keep) is not bool or
                    lang not in (*_LANGS, "unknown")):
                raise ValueError(f"invalid human label {n}")
            labels[line_no] = (line_hash, should_keep, lang)

    rejected = {}
    with (snapshot / "audit.jsonl").open(encoding="utf-8") as audit:
        for line in audit:
            row = json.loads(line)
            number = row.get("line")
            line_hash = row.get("input_line_sha256")
            if (type(number) is not int or number < 1 or
                    number in rejected or not isinstance(line_hash, str) or
                    not _HEX.fullmatch(line_hash)):
                raise ValueError("audit does not provide unique original line decisions")
            rejected[number] = line_hash

    confusion = Counter()
    by_language: dict[str, Counter] = defaultdict(Counter)
    checked = 0
    with original_input.open("r", encoding="utf-8") as source:
        for number, line in enumerate(source, 1):
            digest = hashlib.sha256(line.encode("utf-8")).hexdigest()
            if number in rejected and rejected[number] != digest:
                raise ValueError("audit line hash mismatch with input")
            if number in labels:
                expected_hash, should_keep, lang = labels[number]
                if digest != expected_hash:
                    raise ValueError(f"human label input hash mismatch on line {number}")
                accepted = number not in rejected
                key = ("tp" if should_keep else "fp") if accepted else (
                    "fn" if should_keep else "tn")
                confusion[key] += 1
                by_language[lang][key] += 1
                checked += 1
        lines = number if 'number' in locals() else 0
    if lines != manifest["totals"].get("lines") or checked != len(labels):
        raise ValueError("raw input line count or human-label coverage mismatch")
    if sum(manifest["accepted_splits"].values()) + len(rejected) != lines:
        raise ValueError("audit and manifest decisions do not cover input")
    if max(rejected, default=0) > lines:
        raise ValueError("audit references nonexistent input line")
    return {
        "schema_version": 1,
        "kind": "ada-filter-independent-full-input-evaluation",
        "snapshot_manifest_sha256": file_digest(snapshot / "manifest.json"),
        "original_input_sha256": file_digest(original_input),
        "gold_file_sha256": file_digest(gold_path),
        "input_lines": lines,
        "human_labels": len(labels),
        "labeled_fraction": _safe_fraction(len(labels), lines),
        "metrics": _confusion_metrics(confusion),
        "metrics_by_labeled_language": {
            k: _confusion_metrics(v) for k, v in sorted(by_language.items())
        },
        "limitations": [
            "Gold keep/drop judgments must be independently annotated, adjudicated and sampled.",
            "Precision/recall apply to labeled input lines, not an unobserved population.",
            "This evaluates existing pipeline decisions; it does not prove a causal gain in ADA model quality.",
            "Requires access to the original raw input; only aggregate metrics leave the evaluator.",
        ],
    }
